pub fn from_ntstatus(status: u32) -> Option<u32> {
    match status {
        1 => Some(731), // ERROR_WAIT_1
        2 => Some(732),
        3 => Some(733),
        63 => Some(734), // ERROR_WAIT_63
        // WaitAny can return these indices, which have no Win32 message ID.
        // Their established DOS conversion is ERROR_MR_MID_NOT_FOUND.
        4..=62 => Some(317),
        _ => NTSTATUS_TO_DOS
            .iter()
            .find_map(|&(nt, dos)| (nt == status).then_some(dos)),
    }
}
