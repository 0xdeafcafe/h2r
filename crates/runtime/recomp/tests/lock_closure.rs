//! Tests for the `Cargo.lock` closure that build.rs hashes into
//! `FAST_TIER_SOURCE_HASH` and `ANALYSIS_SOURCE_HASH` (build.rs, the
//! included file is `lock_closure.rs` at the crate root).

#[path = "../lock_closure.rs"]
mod lock_closure;
use lock_closure::{closure_text, fnv_extend};

const LOCK: &str = r#"# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "liba",
 "libb 1.0.0",
 "dup 2.0.0 (registry+https://example.invalid/index)",
]

[[package]]
name = "liba"
version = "0.3.0"
source = "registry+https://example.invalid/index"
checksum = "aaaa"
dependencies = [
 "leaf",
]

[[package]]
name = "libb"
version = "1.0.0"
source = "registry+https://example.invalid/index"
checksum = "bbbb"

[[package]]
name = "libb"
version = "0.9.0"
source = "registry+https://example.invalid/index"
checksum = "b0b0"

[[package]]
name = "dup"
version = "1.0.0"
source = "registry+https://example.invalid/index"
checksum = "d100"

[[package]]
name = "dup"
version = "2.0.0"
source = "registry+https://example.invalid/index"
checksum = "d200"
dependencies = []

[[package]]
name = "leaf"
version = "0.1.0"
source = "registry+https://example.invalid/index"
checksum = "eeee"

[[package]]
name = "unrelated"
version = "5.0.0"
source = "registry+https://example.invalid/index"
checksum = "ffff"
dependencies = [
 "leaf",
]
"#;

fn digest(lock: &str, roots: &[&str]) -> u64 {
    fnv_extend(0xcbf2_9ce4_8422_2325, closure_text(lock, roots).unwrap().as_bytes())
}

#[test]
fn unrelated_package_bump_leaves_hash_unchanged() {
    let bumped = LOCK.replace("name = \"unrelated\"\nversion = \"5.0.0\"", "name = \"unrelated\"\nversion = \"5.1.0\"").replace("\"ffff\"", "\"f00f\"");
    assert_ne!(bumped, LOCK);
    assert_eq!(digest(LOCK, &["app"]), digest(&bumped, &["app"]));
}

#[test]
fn reached_package_change_changes_hash() {
    let base = digest(LOCK, &["app"]);
    // A direct dependency, a transitive one, and a checksum-only change.
    let direct = LOCK.replace("version = \"0.3.0\"", "version = \"0.3.1\"");
    let transitive = LOCK.replace("version = \"0.1.0\"\nsource", "version = \"0.1.1\"\nsource");
    let checksum = LOCK.replace("\"eeee\"", "\"e00e\"");
    for changed in [direct, transitive, checksum] {
        assert_ne!(changed, LOCK);
        assert_ne!(base, digest(&changed, &["app"]));
    }
}

#[test]
fn order_independent() {
    let mut blocks: Vec<&str> = LOCK.split("\n[[package]]\n").collect();
    let head = blocks.remove(0);
    blocks.reverse();
    let shuffled = format!("{head}\n[[package]]\n{}", blocks.join("\n[[package]]\n"));
    assert_ne!(shuffled, LOCK);
    assert_eq!(digest(LOCK, &["app"]), digest(&shuffled, &["app"]));
}

#[test]
fn name_version_dependency_resolves_to_that_version() {
    let text = closure_text(LOCK, &["app"]).unwrap();
    assert!(text.contains("libb 1.0.0 "), "{text}");
    assert!(!text.contains("libb 0.9.0"), "{text}");
    assert!(text.contains("dup 2.0.0 "), "{text}");
    assert!(!text.contains("dup 1.0.0"), "{text}");
    assert!(text.contains("leaf 0.1.0 "), "{text}");
    assert!(!text.contains("unrelated"), "{text}");
    // Bumping the version that was not chosen changes nothing.
    let other = LOCK.replace("\"b0b0\"", "\"c0c0\"").replace("\"d100\"", "\"d101\"");
    assert_eq!(digest(LOCK, &["app"]), digest(&other, &["app"]));
}

#[test]
fn several_roots_and_missing_root() {
    let both = closure_text(LOCK, &["app", "unrelated"]).unwrap();
    assert!(both.contains("unrelated 5.0.0 "));
    assert!(closure_text(LOCK, &["nope"]).is_err());
}
