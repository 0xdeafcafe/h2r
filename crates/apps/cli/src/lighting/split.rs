//! Stage the complete private comparison, then publish it under the caller's name.
use super::OutDir;
use anyhow::{Context, Result, bail, ensure};
use std::fs;
use std::path::{Path, PathBuf};
use viewer::split::{self, LightId};

const USAGE: &str = "usage: h2 lighting split <map> [--bsp N] [--light ID] [--disc ISO] --out DIR
BSP and light default to 0. A number selects a sky light in BSP sky order.
placed:N selects spherical lamp placement N in the scenario. Indices start at zero.
DIR must be new or empty and outside Git. Open DIR/index.html to judge the fit.";

pub(super) fn run(mut args: impl Iterator<Item = String>) -> Result<()> {
    let (mut map, mut disc, mut bsp, mut light, mut out) = (None, None, None, None, None);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--help" | "-h" => {
                println!("{USAGE}");
                return Ok(());
            }
            "--bsp" if bsp.is_none() => bsp = Some(args.next().context("--bsp needs N")?.parse()?),
            "--light" if light.is_none() => {
                let id = args
                    .next()
                    .context("--light needs a sky light ID or placed:N")?;
                light = Some(if let Some(n) = id.strip_prefix("placed:") {
                    LightId::Placed(n.parse().context("expected placed:N")?)
                } else {
                    LightId::Sky(id.parse().context("expected a sky light ID or placed:N")?)
                });
            }
            "--out" if out.is_none() => {
                out = Some(PathBuf::from(args.next().context("--out needs DIR")?))
            }
            "--disc" if disc.is_none() => {
                disc = Some(PathBuf::from(args.next().context("--disc needs ISO")?))
            }
            s if !s.starts_with('-') && map.is_none() => map = Some(arg),
            _ => bail!("unexpected argument {arg}\n{USAGE}"),
        }
    }
    let name = map.context(USAGE)?;
    let out = out.context(USAGE)?;
    let (mut map, mut files) = crate::bitmap::open(&name, disc)?;
    let report = publish(&out, |stage| {
        split::compare(
            &mut map,
            &mut files,
            &name,
            bsp.unwrap_or(0),
            light.unwrap_or(LightId::Sky(0)),
            |file, bytes| {
                // All filenames are generated by the viewer from numeric indices.
                fs::write(stage.join(file), bytes)?;
                Ok(())
            },
        )
    })?;
    println!(
        "{}\nOpen {}",
        report.summary,
        out.join("index.html").display()
    );
    ensure!(
        report.reviewable,
        "split stopped; the contact report gives the reason"
    );
    Ok(())
}

fn publish<T>(out: &Path, work: impl FnOnce(&Path) -> Result<T>) -> Result<T> {
    let absolute = std::env::current_dir()?.join(out);
    let parent = absolute.parent().context("--out needs a named directory")?;
    let name = absolute
        .file_name()
        .context("--out needs a named directory")?;
    ensure!(name != ".git", "refusing output inside Git");
    // new_strict validates every existing component, including platform aliases.
    // Check the physical parent as well as the destination (which may be a checkout).
    OutDir::new_strict(parent, false)?;
    let parent = parent.canonicalize()?;
    let dest = parent.join(name);
    ensure!(
        !dest
            .ancestors()
            .any(|p| p.join(".git").exists() || p.file_name().is_some_and(|n| n == ".git")),
        "refusing output inside Git: {}",
        dest.display()
    );
    match fs::symlink_metadata(&dest) {
        Ok(meta) => ensure!(
            meta.is_dir() && fs::read_dir(&dest)?.next().is_none(),
            "{} must be a new or empty directory",
            dest.display()
        ),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
        Err(e) => return Err(e.into()),
    }
    let stage = parent.join(format!(".h2-lighting-split-{}", std::process::id()));
    ensure!(stage != dest, "reserved output directory");
    fs::create_dir(&stage).context("reserve lighting comparison staging directory")?;
    let result = work(&stage).and_then(|value| {
        // Windows cannot rename a directory over an existing empty directory.
        #[cfg(windows)]
        if let Err(e) = fs::remove_dir(&dest) {
            if e.kind() != std::io::ErrorKind::NotFound {
                return Err(e.into());
            }
        }
        fs::rename(&stage, &dest).with_context(|| format!("publish {}", dest.display()))?;
        Ok(value)
    });
    if result.is_err() {
        fs::remove_dir_all(&stage).with_context(|| format!("clean up {}", stage.display()))?;
    }
    result
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn private_output_is_retryable_and_refuses_git_and_existing_results() {
        let root = std::env::temp_dir()
            .canonicalize()
            .unwrap()
            .join(format!("h2-split-publish-test-{}", std::process::id()));
        fs::create_dir(&root).unwrap();
        let checkout = root.join("worktree");
        fs::create_dir(&checkout).unwrap();
        fs::write(checkout.join(".git"), "gitdir: invented").unwrap();
        let forbidden = checkout.join("report");
        assert!(publish(&forbidden, |_| Ok(())).is_err());
        assert!(!forbidden.exists());

        let out = root.join("report");
        assert!(
            publish(&out, |stage| -> Result<()> {
                fs::write(stage.join("page.png"), b"invented")?;
                bail!("injected failure")
            })
            .is_err()
        );
        assert!(!out.exists());
        fs::create_dir(&out).unwrap();
        publish(&out, |stage| {
            Ok(fs::write(stage.join("index.html"), "complete")?)
        })
        .unwrap();
        assert!(publish(&out, |_| Ok(())).is_err());
        assert_eq!(
            fs::read_to_string(out.join("index.html")).unwrap(),
            "complete"
        );
        fs::remove_dir_all(root).unwrap();
    }
}
