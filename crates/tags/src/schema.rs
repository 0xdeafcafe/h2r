//! Tag layout schemas inferred from retail maps, and relocation with them.
//!
//! The retail executable carries no tag field definitions, so these layouts
//! come from data: [`infer`] reads every instance of every group across a set
//! of maps and keeps a field only where all instances agree (see
//! `docs/formats/tag-schema.md`). A [`Schema`] records, per group, the root
//! element size and every layout-dependent field: tag blocks and data
//! references (with their child layout), tag references, bare datums and
//! string IDs. Everything else is copied as bytes.
//!
//! [`to_built`] turns a pinned retail tag into a [`map::build::Block`] tree
//! with a fixup for every pointer, so the builder can lay it out anywhere. It
//! refuses (with a [`Refusal`]) unless the tree covers the tag's bytes exactly
//! once and no uncovered word looks like an address in the tag or metadata.
use map::build::{Block, FixupKind};
use map::{FourCC, Map, TagId};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::io::{Read, Seek};

pub mod infer;

/// The checked-in schema, generated by `infer` over the retail disc and map
/// pack (see the doc for the command). Offsets and sizes only.
pub const BUILTIN: &str = include_str!("schema/layouts.txt");

/// Largest alignment inferred for a block.
pub const MAX_ALIGN: u32 = 16;

/// One element layout: its size, alignment and layout-dependent fields.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Struct {
    /// Element size in bytes (stride of the array).
    pub size: u32,
    /// Alignment of the array's address (power of two, at most [`MAX_ALIGN`]).
    pub align: u32,
    /// Layout-dependent fields by offset in the element.
    pub fields: BTreeMap<u32, Field>,
}

/// A layout-dependent field.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Field {
    /// 8 bytes: count, then the address of `count` elements of the child.
    /// A data reference is a block of 1-byte elements with no fields.
    Block(Box<Struct>),
    /// 8 bytes: group, then datum.
    TagRef,
    /// 4 bytes: a datum.
    TagId,
    /// 4 bytes: a string ID (`index | length << 24`).
    StringId,
}

impl Field {
    /// Bytes the field occupies.
    pub fn width(&self) -> u32 {
        match self {
            Field::Block(_) | Field::TagRef => 8,
            Field::TagId | Field::StringId => 4,
        }
    }
}

/// Per-group root layouts.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Schema {
    /// Root element of each group (count 1, at the tag's address).
    pub groups: BTreeMap<FourCC, Struct>,
}

/// Why a tag cannot be relocated with the schema.
#[derive(Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Refusal {
    /// The schema has no layout for the group.
    NoSchema,
    /// The tag has no ordinary metadata.
    NoData,
    /// A block points outside the tag, or its elements run past the end.
    OutOfBounds,
    /// Two arrays share bytes (aliasing).
    Overlap,
    /// Bytes no element covers, other than zero alignment padding.
    Uncovered,
    /// A word outside every known field holds an address in the tag or in
    /// the metadata (an undescribed pointer).
    UnknownPointer,
    /// The tag lives in a BSP region; those move with their region (not
    /// handled here).
    BspRegion,
}

impl std::fmt::Display for Refusal {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(match self {
            Refusal::NoSchema => "no schema for the group",
            Refusal::NoData => "no ordinary metadata",
            Refusal::OutOfBounds => "block out of bounds",
            Refusal::Overlap => "arrays overlap",
            Refusal::Uncovered => "bytes not covered by the layout",
            Refusal::UnknownPointer => "undescribed pointer",
            Refusal::BspRegion => "tag in a BSP region",
        })
    }
}

impl Schema {
    /// The checked-in schema.
    pub fn builtin() -> &'static Schema {
        static SCHEMA: std::sync::OnceLock<Schema> = std::sync::OnceLock::new();
        SCHEMA.get_or_init(|| Schema::parse(BUILTIN).expect("checked-in schema parses"))
    }

    /// Text form: one line per group or field, children indented by two
    /// spaces under their block. See [`Schema::parse`].
    pub fn to_text(&self) -> String {
        fn fields(out: &mut String, s: &Struct, depth: usize) {
            for (offset, field) in &s.fields {
                let pad = "  ".repeat(depth);
                match field {
                    Field::Block(child) => {
                        let _ = writeln!(
                            out,
                            "{pad}{offset:#x} block {:#x} align {}",
                            child.size, child.align
                        );
                        fields(out, child, depth + 1);
                    }
                    Field::TagRef => {
                        let _ = writeln!(out, "{pad}{offset:#x} tagref");
                    }
                    Field::TagId => {
                        let _ = writeln!(out, "{pad}{offset:#x} datum");
                    }
                    Field::StringId => {
                        let _ = writeln!(out, "{pad}{offset:#x} string");
                    }
                }
            }
        }
        let mut out = String::new();
        for (group, root) in &self.groups {
            let _ = writeln!(
                out,
                "group {} {:#x} align {}",
                hex_fourcc(*group),
                root.size,
                root.align
            );
            fields(&mut out, root, 1);
        }
        out
    }

    /// Parse [`Schema::to_text`]. Lines starting with `#` are comments.
    /// A group line is `group <name> <size> align <n>` (the name as 4
    /// characters, or 8 hex digits, see [`hex_fourcc`]);
    /// field lines are `<offset> block <size> align <n>`, `<offset> tagref`,
    /// `<offset> datum` or `<offset> string`, indented two spaces per level.
    pub fn parse(text: &str) -> Result<Schema, String> {
        let mut schema = Schema::default();
        // Stack of (depth, path of offsets from the group root).
        let mut group: Option<FourCC> = None;
        let mut stack: Vec<u32> = Vec::new();
        for (n, line) in text.lines().enumerate() {
            let err = |m: &str| format!("line {}: {m}", n + 1);
            if line.trim().is_empty() || line.trim_start().starts_with('#') {
                continue;
            }
            let indent = line.len() - line.trim_start().len();
            let words: Vec<&str> = line.split_whitespace().collect();
            let num = |s: &str| {
                let v = s.strip_prefix("0x").map_or_else(
                    || s.parse::<u32>().ok(),
                    |h| u32::from_str_radix(h, 16).ok(),
                );
                v.ok_or_else(|| err("bad number"))
            };
            if words[0] == "group" {
                if words.len() != 5 || words[3] != "align" {
                    return Err(err("bad group line"));
                }
                let g = parse_fourcc(words[1]).ok_or_else(|| err("bad group"))?;
                let root = Struct {
                    size: num(words[2])?,
                    align: num(words[4])?,
                    fields: BTreeMap::new(),
                };
                schema.groups.insert(g, root);
                group = Some(g);
                stack.clear();
                continue;
            }
            let g = group.ok_or_else(|| err("field before group"))?;
            if indent % 2 != 0 || indent < 2 {
                return Err(err("bad indent"));
            }
            let depth = indent / 2 - 1;
            if depth > stack.len() {
                return Err(err("indent skips a level"));
            }
            stack.truncate(depth);
            let mut parent = schema.groups.get_mut(&g).expect("inserted");
            for o in &stack {
                parent = match parent.fields.get_mut(o) {
                    Some(Field::Block(c)) => c,
                    _ => return Err(err("parent is not a block")),
                };
            }
            let offset = num(words[0])?;
            let field = match words.get(1).copied() {
                Some("block") if words.len() == 5 && words[3] == "align" => {
                    stack.push(offset);
                    Field::Block(Box::new(Struct {
                        size: num(words[2])?,
                        align: num(words[4])?,
                        fields: BTreeMap::new(),
                    }))
                }
                Some("tagref") => Field::TagRef,
                Some("datum") => Field::TagId,
                Some("string") => Field::StringId,
                _ => return Err(err("bad field")),
            };
            if offset + field.width() > parent.size {
                return Err(err("field past the element"));
            }
            parent.fields.insert(offset, field);
        }
        Ok(schema)
    }
}

/// A group as its four characters, or as 8 hex digits of its numeric
/// value when it holds a space or an unprintable byte.
pub fn hex_fourcc(g: FourCC) -> String {
    if g.0.iter().all(u8::is_ascii_graphic) {
        g.0.iter().map(|&b| b as char).collect()
    } else {
        format!("{:08x}", g.as_u32())
    }
}

fn parse_fourcc(s: &str) -> Option<FourCC> {
    match s.len() {
        4 => Some(FourCC(s.as_bytes().try_into().ok()?)),
        8 => u32::from_str_radix(s, 16).ok().map(FourCC::from_u32),
        _ => None,
    }
}

/// A tag walked with a schema.
#[derive(Clone, Debug, Default)]
pub struct Walk {
    /// Arrays inside the tag, as (offset in the tag, byte length), sorted.
    pub arrays: Vec<(u32, u32)>,
    /// Arrays in other tags' bytes (blocks the cache compiler shared between
    /// identical tags), as (address, byte length). The built tree copies them.
    pub foreign: Vec<(u32, u32)>,
}

fn u32_at(bytes: &[u8], at: usize) -> u32 {
    u32::from_le_bytes(bytes[at..at + 4].try_into().expect("4 bytes"))
}

/// Tag bytes by address: every ordinary-metadata tag of a map, so blocks
/// shared between tags can be followed.
#[derive(Clone, Debug, Default)]
pub struct Memory {
    /// (address, bytes), sorted by address, not overlapping.
    regions: Vec<(u32, Vec<u8>)>,
    /// Address ranges no undescribed word may point into.
    spaces: Vec<(u32, u32)>,
}

impl Memory {
    /// Every ordinary-metadata tag of `map`, and its address spaces (the
    /// metadata region and every BSP region).
    pub fn of<R: Read + Seek>(map: &mut Map<R>) -> crate::Result<Self> {
        let mut spaces = Vec::new();
        let meta = map.metadata_space();
        if let Some(s) = meta {
            spaces.push((s.virtual_base, s.virtual_base.saturating_add(s.size)));
        }
        let mut regions = Vec::new();
        for t in map.tags().to_vec() {
            let Some(l) = t.location else { continue };
            if Some(l.space) == meta {
                if l.size > 0 {
                    regions.push((l.address, map.read_tag_bytes(t.id)?));
                }
            } else {
                let r = (
                    l.space.virtual_base,
                    l.space.virtual_base.saturating_add(l.space.size),
                );
                if !spaces.contains(&r) {
                    spaces.push(r);
                }
            }
        }
        regions.sort_by_key(|r| r.0);
        Ok(Memory { regions, spaces })
    }

    /// Memory holding only these regions (for tests and BSP tags).
    pub fn from_regions(mut regions: Vec<(u32, Vec<u8>)>, spaces: Vec<(u32, u32)>) -> Self {
        regions.sort_by_key(|r| r.0);
        Memory { regions, spaces }
    }

    /// The region (address, bytes) holding `address`.
    pub fn region(&self, address: u32) -> Option<(u32, &[u8])> {
        let i = self
            .regions
            .partition_point(|r| r.0 <= address)
            .checked_sub(1)?;
        let (a, b) = &self.regions[i];
        (address - a < b.len() as u32).then_some((*a, b.as_slice()))
    }

    /// `n` bytes at `address`, inside one region.
    pub fn slice(&self, address: u32, n: u32) -> Option<&[u8]> {
        let (a, b) = self.region(address)?;
        let at = (address - a) as usize;
        b.get(at..at.checked_add(n as usize)?)
    }

    fn hit(&self, v: u32) -> bool {
        self.spaces.iter().any(|&(lo, hi)| (lo..hi).contains(&v))
    }
}

/// Where a [`walk`] refused: the reason, the field path (block offsets from
/// the root) and the offset in the element (or in the tag, for coverage).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Detail {
    /// Why.
    pub refusal: Refusal,
    /// Offsets of the blocks followed from the root.
    pub path: Vec<u32>,
    /// Offset in the element, or in the tag for [`Refusal::Overlap`] and
    /// [`Refusal::Uncovered`].
    pub offset: u32,
    /// The value found (for [`Refusal::UnknownPointer`]).
    pub value: u32,
}

/// Walk the tag at `address` (its bytes in `mem`) with `root`. The arrays
/// inside the tag must tile it (exact duplicates allowed: the compiler
/// shares identical blocks), arrays outside it must sit inside one other
/// tag, and no undescribed word may hold an address in a known space.
pub fn walk(root: &Struct, address: u32, mem: &Memory) -> Result<Walk, Detail> {
    let fail = |refusal, path: &[u32], offset, value| Detail {
        refusal,
        path: path.to_vec(),
        offset,
        value,
    };
    let Some((start, own)) = mem.region(address).filter(|r| r.0 == address) else {
        return Err(fail(Refusal::NoData, &[], 0, address));
    };
    debug_assert_eq!(start, address);
    let len = own.len() as u32;
    let end = address + len;
    let mut out = Walk::default();
    // (struct, address, count, path)
    let mut todo: Vec<(&Struct, u32, u32, Vec<u32>)> = vec![(root, address, 1, Vec::new())];
    let mut seen = std::collections::HashSet::new();
    while let Some((s, at, count, path)) = todo.pop() {
        let n = u64::from(s.size) * u64::from(count);
        let Some(bytes) = u32::try_from(n).ok().and_then(|n| mem.slice(at, n)) else {
            return Err(fail(Refusal::OutOfBounds, &path, at, count));
        };
        let n = n as u32;
        // Shared arrays are followed once per layout.
        if !seen.insert((at, n, s as *const Struct)) {
            continue;
        }
        if (address..end).contains(&at) {
            out.arrays.push((at - address, n));
        } else {
            out.foreign.push((at, n));
        }
        for i in 0..count {
            let e = (i * s.size) as usize;
            let elem = &bytes[e..e + s.size as usize];
            let mut covered = vec![false; elem.len()];
            for (&o, f) in &s.fields {
                covered[o as usize..(o + f.width()) as usize].fill(true);
            }
            for k in (0..elem.len().saturating_sub(3)).step_by(4) {
                if covered[k..k + 4].iter().any(|c| *c) {
                    continue;
                }
                let v = u32_at(elem, k);
                if (address..end).contains(&v) || mem.hit(v) {
                    return Err(fail(Refusal::UnknownPointer, &path, k as u32, v));
                }
            }
            for (&o, f) in &s.fields {
                if let Field::Block(child) = f {
                    let c = u32_at(elem, o as usize);
                    let a = u32_at(elem, o as usize + 4);
                    let mut sub = path.clone();
                    sub.push(o);
                    // Empty (the builder writes address zero), or a count
                    // with a null address, kept as bytes.
                    if c == 0 || a == 0 {
                        continue;
                    }
                    todo.push((child, a, c, sub));
                }
            }
        }
    }
    out.arrays.sort_unstable();
    out.arrays.dedup();
    let mut pos = 0u32;
    for &(at, n) in &out.arrays {
        if n == 0 {
            continue;
        }
        if at < pos {
            return Err(fail(Refusal::Overlap, &[], at, pos));
        }
        // Gaps must be zero padding shorter than the largest alignment.
        if at - pos >= MAX_ALIGN || own[pos as usize..at as usize].iter().any(|b| *b != 0) {
            return Err(fail(Refusal::Uncovered, &[], pos, at - pos));
        }
        pos = at + n;
    }
    if len - pos >= MAX_ALIGN || own[pos as usize..].iter().any(|b| *b != 0) {
        return Err(fail(Refusal::Uncovered, &[], pos, len - pos));
    }
    Ok(out)
}

/// Build the block tree for `count` elements of `s` at `at`. Tag references,
/// datums and string IDs keep their bytes: in the same tag set they stay
/// valid. Moving tags between maps rewrites them (see [`remap`]).
fn tree(s: &Struct, mem: &Memory, at: u32, count: u32) -> Block {
    let bytes = mem.slice(at, s.size * count).expect("walked");
    let mut block = Block::new(bytes.to_vec()).aligned(s.align);
    for i in 0..count {
        let e = (i * s.size) as usize;
        for (&o, f) in &s.fields {
            if let Field::Block(child) = f {
                let c = u32_at(bytes, e + o as usize);
                let a = u32_at(bytes, e + o as usize + 4);
                if c != 0 && a == 0 {
                    // A count with a null address: no child, bytes kept.
                    continue;
                }
                let sub = if c == 0 {
                    Block::zeroed(0).aligned(child.align)
                } else {
                    tree(child, mem, a, c)
                };
                let off = i * s.size + o;
                if child.size == 1 && child.fields.is_empty() {
                    block.fixup(off, FixupKind::Data(sub));
                } else {
                    block.block(off, c, sub);
                }
            }
        }
    }
    block
}

/// Relocates the tags of one map with a schema.
pub struct Relocator<'s> {
    schema: &'s Schema,
    memory: Memory,
    tags: Vec<map::Tag>,
    metadata: Option<map::AddressSpace>,
}

impl<'s> Relocator<'s> {
    /// Read `map`'s metadata once.
    pub fn new<R: Read + Seek>(schema: &'s Schema, map: &mut Map<R>) -> crate::Result<Self> {
        Ok(Relocator {
            schema,
            memory: Memory::of(map)?,
            tags: map.tags().to_vec(),
            metadata: map.metadata_space(),
        })
    }

    /// The map's metadata.
    pub fn memory(&self) -> &Memory {
        &self.memory
    }

    fn tag(&self, id: TagId) -> Option<&map::Tag> {
        self.tags.iter().find(|t| t.id == id)
    }

    /// Check one tag; `Ok` means [`Relocator::to_built`] will succeed.
    pub fn check(&self, id: TagId) -> Result<Walk, Detail> {
        let fail = |refusal| Detail {
            refusal,
            path: Vec::new(),
            offset: 0,
            value: 0,
        };
        let tag = self.tag(id).ok_or(fail(Refusal::NoData))?;
        let Some(root) = self.schema.groups.get(&tag.group) else {
            return Err(fail(Refusal::NoSchema));
        };
        match tag.location {
            None => Err(fail(Refusal::NoData)),
            Some(l) if Some(l.space) != self.metadata => Err(fail(Refusal::BspRegion)),
            Some(l) => walk(root, l.address, &self.memory),
        }
    }

    /// The tag as a relocatable tree, or why not.
    pub fn to_built(&self, id: TagId) -> Result<Block, Refusal> {
        self.check(id).map_err(|d| d.refusal)?;
        let tag = self.tag(id).expect("checked");
        let root = &self.schema.groups[&tag.group];
        Ok(tree(
            root,
            &self.memory,
            tag.location.expect("checked").address,
            1,
        ))
    }

    /// Tags that can move together: every tag [`Relocator::check`] accepts,
    /// minus those a staying tag points into (any aligned word of a pinned
    /// tag holding an address inside them), repeated until nothing changes.
    pub fn movable(&self) -> Vec<TagId> {
        self.movable_where(|_| true)
    }

    /// [`Relocator::movable`], starting from the accepted tags whose walk
    /// passes `keep` (e.g. no shared arrays, which the tree copies and so
    /// grows the metadata).
    pub fn movable_where(&self, keep: impl Fn(&Walk) -> bool) -> Vec<TagId> {
        let mut ok: std::collections::BTreeSet<u32> = self
            .tags
            .iter()
            .filter(|t| self.check(t.id).is_ok_and(|w| keep(&w)))
            .map(|t| t.location.expect("checked").address)
            .collect();
        loop {
            let mut pinned_targets = Vec::new();
            for (a, bytes) in &self.memory.regions {
                if ok.contains(a) {
                    continue;
                }
                for w in bytes.as_chunks::<4>().0 {
                    let v = u32::from_le_bytes(*w);
                    if let Some((t, _)) = self.memory.region(v)
                        && t != *a
                        && ok.contains(&t)
                    {
                        pinned_targets.push(t);
                    }
                }
            }
            if pinned_targets.is_empty() {
                break;
            }
            for t in pinned_targets {
                ok.remove(&t);
            }
        }
        self.tags
            .iter()
            .filter(|t| {
                t.location
                    .is_some_and(|l| Some(l.space) == self.metadata && ok.contains(&l.address))
            })
            .map(|t| t.id)
            .collect()
    }
}

/// Turn the tag `id` of `map` into a relocatable block tree with `schema`.
/// Reads the map's whole metadata; for many tags use a [`Relocator`].
pub fn to_built_with<R: Read + Seek>(
    schema: &Schema,
    map: &mut Map<R>,
    id: TagId,
) -> crate::Result<Result<Block, Refusal>> {
    Ok(Relocator::new(schema, map)?.to_built(id))
}

/// [`to_built_with`] using the checked-in schema.
pub fn to_built<R: Read + Seek>(
    map: &mut Map<R>,
    id: TagId,
) -> crate::Result<Result<Block, Refusal>> {
    to_built_with(Schema::builtin(), map, id)
}

/// A decoded tag tree with every address removed: each array's element
/// bytes with block addresses zeroed, followed by its children in field
/// order. Two tags with equal trees hold the same data wherever they sit.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Tree {
    /// Element bytes, block address words zeroed.
    pub bytes: Vec<u8>,
    /// Child arrays, in element then field order.
    pub children: Vec<Tree>,
}

/// Read the address-free [`Tree`] of the tag at `address`.
pub fn read_tree(root: &Struct, address: u32, mem: &Memory) -> Option<Tree> {
    fn go(s: &Struct, mem: &Memory, at: u32, count: u32, depth: u32) -> Option<Tree> {
        if depth > 64 {
            return None;
        }
        let mut own = mem.slice(at, s.size.checked_mul(count)?)?.to_vec();
        let mut children = Vec::new();
        for i in 0..count {
            let e = (i * s.size) as usize;
            for (&o, f) in &s.fields {
                if let Field::Block(child) = f {
                    let o = e + o as usize;
                    let c = u32_at(&own, o);
                    let a = u32_at(&own, o + 4);
                    own[o + 4..o + 8].fill(0);
                    children.push(if c == 0 || a == 0 {
                        Tree {
                            bytes: Vec::new(),
                            children: Vec::new(),
                        }
                    } else {
                        go(child, mem, a, c, depth + 1)?
                    });
                }
            }
        }
        Some(Tree {
            bytes: own,
            children,
        })
    }
    go(root, mem, address, 1, 0)
}

/// Rewrite the tag references, datums and string IDs of a tree built from
/// one map so it is valid in another. `datum` maps a source datum to the
/// destination's (`None` for a datum outside the copied graph: the field is
/// nulled); `string` maps a source string ID to the destination's.
pub fn remap(
    s: &Struct,
    block: &mut Block,
    count: u32,
    datum: &mut dyn FnMut(u32) -> Option<u32>,
    string: &mut dyn FnMut(u32) -> u32,
    group_of: &mut dyn FnMut(u32) -> Option<u32>,
) {
    for i in 0..count {
        for (&o, f) in &s.fields {
            let at = (i * s.size + o) as usize;
            match f {
                Field::TagRef => {
                    let d = u32_at(&block.bytes, at + 4);
                    if d != u32::MAX {
                        let (g, nd) = match datum(d) {
                            Some(nd) => (u32_at(&block.bytes, at), nd),
                            None => (u32::MAX, u32::MAX),
                        };
                        let g = if g == u32::MAX {
                            group_of(d).unwrap_or(g)
                        } else {
                            g
                        };
                        let g = if nd == u32::MAX { u32::MAX } else { g };
                        block.bytes[at..at + 4].copy_from_slice(&g.to_le_bytes());
                        block.bytes[at + 4..at + 8].copy_from_slice(&nd.to_le_bytes());
                    }
                }
                Field::TagId => {
                    let d = u32_at(&block.bytes, at);
                    if d != u32::MAX {
                        let nd = datum(d).unwrap_or(u32::MAX);
                        block.bytes[at..at + 4].copy_from_slice(&nd.to_le_bytes());
                    }
                }
                Field::StringId => {
                    let v = u32_at(&block.bytes, at);
                    if v != 0 {
                        let nv = string(v);
                        block.bytes[at..at + 4].copy_from_slice(&nv.to_le_bytes());
                    }
                }
                Field::Block(child) => {
                    let off = i * s.size + o;
                    let c = u32_at(&block.bytes, at);
                    if let Some(fx) = block.fixups.iter_mut().find(|x| x.offset == off) {
                        match &mut fx.kind {
                            FixupKind::Block { child: sub, .. } | FixupKind::Data(sub) => {
                                remap(child, sub, c, datum, string, group_of);
                            }
                            _ => {}
                        }
                    }
                }
            }
        }
    }
}

