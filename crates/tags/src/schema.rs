//! Tag layout schemas inferred from retail maps, and relocation with them.
//!
//! The retail executable carries no tag field definitions, so these layouts
//! come from data: [`infer`] reads every instance of every group across a set
//! of maps and keeps a field only where all instances agree (see
//! `docs/formats/tag-schema.md`). A [`Schema`] records, per group, the root
//! element size and every layout-dependent field: tag blocks and data
//! references (with their child layout), tag references, bare datums and
//! string IDs. Everything else is copied as bytes.
//!
//! [`to_built`] turns a pinned retail tag into a [`map::build::Block`] tree
//! with a fixup for every pointer, so the builder can lay it out anywhere. It
//! refuses (with a [`Refusal`]) unless the tree covers the tag's bytes exactly
//! once and no uncovered word looks like an address in the tag or metadata.
use map::build::{Block, FixupKind, RawRef};
use map::{FourCC, Map, TagId};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::io::{Read, Seek};

pub mod infer;
pub mod transplant;

/// The checked-in schema, generated by `infer` over the retail disc and map
/// pack (see the doc for the command). Offsets and sizes only.
pub const BUILTIN: &str = include_str!("schema/layouts.txt");

/// Largest alignment inferred for a block.
pub const MAX_ALIGN: u32 = 16;

/// One element layout: its size, alignment and layout-dependent fields.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Struct {
    /// Element size in bytes (stride of the array).
    pub size: u32,
    /// Alignment of the array's address (power of two, at most [`MAX_ALIGN`]).
    pub align: u32,
    /// Layout-dependent fields by offset in the element.
    pub fields: BTreeMap<u32, Field>,
}

/// A layout-dependent field.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Field {
    /// 8 bytes: count, then the address of `count` elements of the child.
    /// A data reference is a block of 1-byte elements with no fields.
    Block(Box<Struct>),
    /// 8 bytes: group, then datum.
    TagRef,
    /// 4 bytes: a datum.
    TagId,
    /// 4 bytes: a string ID (`index | length << 24`).
    StringId,
    /// 4 bytes: a raw-resource pointer (selector in the top two bits, file
    /// offset below; `0xffffffff` is null).
    Raw,
    /// 12 bytes: a BSP region's file offset, size and load address (the
    /// scenario's structure BSP descriptors, `scnr +0x210`). All zero, or
    /// one of the map's BSP regions. Kept as bytes: relocating ordinary
    /// metadata leaves BSP regions where they are; a builder that rebuilds
    /// a region writes [`map::build::FixupKind::Bsp`] here instead.
    Bsp,
    /// 4 bytes of plain data whose values can fall in an address space
    /// (packed 16-bit indices with flag bits, say) but are not pointers:
    /// some instance holds an unaligned one. Kept as bytes.
    Word,
    /// 4 bytes: the byte length of the raw resource whose pointer is the
    /// [`Field::Raw`] at this offset of the same element.
    RawSize(u32),
}

impl Field {
    /// Bytes the field occupies.
    pub fn width(&self) -> u32 {
        match self {
            Field::Block(_) | Field::TagRef => 8,
            Field::TagId | Field::StringId | Field::Raw | Field::Word | Field::RawSize(_) => 4,
            Field::Bsp => 12,
        }
    }
}

/// Per-group root layouts.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Schema {
    /// Root element of each group (count 1, at the tag's address).
    pub groups: BTreeMap<FourCC, Struct>,
}

/// Why a tag cannot be relocated with the schema.
#[derive(Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Refusal {
    /// The schema has no layout for the group.
    NoSchema,
    /// The tag has no ordinary metadata.
    NoData,
    /// A block points outside the tag, or its elements run past the end.
    OutOfBounds,
    /// Two arrays share bytes (aliasing).
    Overlap,
    /// Bytes no element covers, other than zero alignment padding.
    Uncovered,
    /// A word outside every known field holds an address in the tag or in
    /// the metadata (an undescribed pointer).
    UnknownPointer,
    /// The tag lives in a BSP region; those move with their region (not
    /// handled here).
    BspRegion,
}

impl std::fmt::Display for Refusal {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(match self {
            Refusal::NoSchema => "no schema for the group",
            Refusal::NoData => "no ordinary metadata",
            Refusal::OutOfBounds => "block out of bounds",
            Refusal::Overlap => "arrays overlap",
            Refusal::Uncovered => "bytes not covered by the layout",
            Refusal::UnknownPointer => "undescribed pointer",
            Refusal::BspRegion => "tag in a BSP region",
        })
    }
}

impl Schema {
    /// The checked-in schema.
    pub fn builtin() -> &'static Schema {
        static SCHEMA: std::sync::OnceLock<Schema> = std::sync::OnceLock::new();
        SCHEMA.get_or_init(|| Schema::parse(BUILTIN).expect("checked-in schema parses"))
    }

    /// Text form: one line per group or field, children indented by two
    /// spaces under their block. See [`Schema::parse`].
    pub fn to_text(&self) -> String {
        fn fields(out: &mut String, s: &Struct, depth: usize) {
            for (offset, field) in &s.fields {
                let pad = "  ".repeat(depth);
                match field {
                    Field::Block(child) => {
                        let _ = writeln!(
                            out,
                            "{pad}{offset:#x} block {:#x} align {}",
                            child.size, child.align
                        );
                        fields(out, child, depth + 1);
                    }
                    Field::TagRef => {
                        let _ = writeln!(out, "{pad}{offset:#x} tagref");
                    }
                    Field::TagId => {
                        let _ = writeln!(out, "{pad}{offset:#x} datum");
                    }
                    Field::StringId => {
                        let _ = writeln!(out, "{pad}{offset:#x} string");
                    }
                    Field::Raw => {
                        let _ = writeln!(out, "{pad}{offset:#x} raw");
                    }
                    Field::Bsp => {
                        let _ = writeln!(out, "{pad}{offset:#x} bsp");
                    }
                    Field::Word => {
                        let _ = writeln!(out, "{pad}{offset:#x} word");
                    }
                    Field::RawSize(of) => {
                        let _ = writeln!(out, "{pad}{offset:#x} size {of:#x}");
                    }
                }
            }
        }
        let mut out = String::new();
        for (group, root) in &self.groups {
            let _ = writeln!(
                out,
                "group {} {:#x} align {}",
                hex_fourcc(*group),
                root.size,
                root.align
            );
            fields(&mut out, root, 1);
        }
        out
    }

    /// Parse [`Schema::to_text`]. Lines starting with `#` are comments.
    /// A group line is `group <name> <size> align <n>` (the name as 4
    /// characters, or 8 hex digits, see [`hex_fourcc`]);
    /// field lines are `<offset> block <size> align <n>`, `<offset> tagref`,
    /// `<offset> datum` or `<offset> string`, indented two spaces per level.
    pub fn parse(text: &str) -> Result<Schema, String> {
        let mut schema = Schema::default();
        // Stack of (depth, path of offsets from the group root).
        let mut group: Option<FourCC> = None;
        let mut stack: Vec<u32> = Vec::new();
        for (n, line) in text.lines().enumerate() {
            let err = |m: &str| format!("line {}: {m}", n + 1);
            if line.trim().is_empty() || line.trim_start().starts_with('#') {
                continue;
            }
            let indent = line.len() - line.trim_start().len();
            let words: Vec<&str> = line.split_whitespace().collect();
            let num = |s: &str| {
                let v = s.strip_prefix("0x").map_or_else(
                    || s.parse::<u32>().ok(),
                    |h| u32::from_str_radix(h, 16).ok(),
                );
                v.ok_or_else(|| err("bad number"))
            };
            if words[0] == "group" {
                if words.len() != 5 || words[3] != "align" {
                    return Err(err("bad group line"));
                }
                let g = parse_fourcc(words[1]).ok_or_else(|| err("bad group"))?;
                let root = Struct {
                    size: num(words[2])?,
                    align: num(words[4])?,
                    fields: BTreeMap::new(),
                };
                schema.groups.insert(g, root);
                group = Some(g);
                stack.clear();
                continue;
            }
            let g = group.ok_or_else(|| err("field before group"))?;
            if indent % 2 != 0 || indent < 2 {
                return Err(err("bad indent"));
            }
            let depth = indent / 2 - 1;
            if depth > stack.len() {
                return Err(err("indent skips a level"));
            }
            stack.truncate(depth);
            let mut parent = schema.groups.get_mut(&g).expect("inserted");
            for o in &stack {
                parent = match parent.fields.get_mut(o) {
                    Some(Field::Block(c)) => c,
                    _ => return Err(err("parent is not a block")),
                };
            }
            let offset = num(words[0])?;
            let field = match words.get(1).copied() {
                Some("block") if words.len() == 5 && words[3] == "align" => {
                    stack.push(offset);
                    Field::Block(Box::new(Struct {
                        size: num(words[2])?,
                        align: num(words[4])?,
                        fields: BTreeMap::new(),
                    }))
                }
                Some("tagref") => Field::TagRef,
                Some("datum") => Field::TagId,
                Some("string") => Field::StringId,
                Some("raw") => Field::Raw,
                Some("bsp") => Field::Bsp,
                Some("word") => Field::Word,
                Some("size") => Field::RawSize(num(words.get(2).copied().unwrap_or(""))?),
                _ => return Err(err("bad field")),
            };
            if offset + field.width() > parent.size {
                return Err(err("field past the element"));
            }
            parent.fields.insert(offset, field);
        }
        Ok(schema)
    }
}

/// A group as its four characters, or as 8 hex digits of its numeric
/// value when it holds a space or an unprintable byte.
pub fn hex_fourcc(g: FourCC) -> String {
    if g.0.iter().all(u8::is_ascii_graphic) {
        g.0.iter().map(|&b| b as char).collect()
    } else {
        format!("{:08x}", g.as_u32())
    }
}

fn parse_fourcc(s: &str) -> Option<FourCC> {
    match s.len() {
        4 => Some(FourCC(s.as_bytes().try_into().ok()?)),
        8 => u32::from_str_radix(s, 16).ok().map(FourCC::from_u32),
        _ => None,
    }
}

/// A tag walked with a schema.
#[derive(Clone, Debug, Default)]
pub struct Walk {
    /// Arrays inside the tag, as (offset in the tag, byte length), sorted.
    pub arrays: Vec<(u32, u32)>,
    /// Arrays in other tags' bytes (blocks the cache compiler shared between
    /// identical tags), as (address, byte length). The built tree copies them.
    pub foreign: Vec<(u32, u32)>,
    /// Non-empty block and data-reference fields in the tag's own bytes, as
    /// (offset in the tag, count, target address), sorted, one per field.
    pub pointers: Vec<(u32, u32, u32)>,
}

fn u32_at(bytes: &[u8], at: usize) -> u32 {
    u32::from_le_bytes(bytes[at..at + 4].try_into().expect("4 bytes"))
}

/// Tag bytes by address: every ordinary-metadata tag of a map, so blocks
/// shared between tags can be followed.
#[derive(Clone, Debug, Default)]
pub struct Memory {
    /// (address, bytes), sorted by address, not overlapping.
    regions: Vec<(u32, Vec<u8>)>,
    /// Address ranges no undescribed word may point into.
    spaces: Vec<(u32, u32)>,
    /// BSP regions: (file offset, size, load address).
    pub(crate) bsps: Vec<(u32, u32, u32)>,
}

impl Memory {
    /// Every ordinary-metadata tag of `map`, and its address spaces (the
    /// metadata region and every BSP region).
    pub fn of<R: Read + Seek>(map: &mut Map<R>) -> crate::Result<Self> {
        let mut spaces = Vec::new();
        let meta = map.metadata_space();
        if let Some(s) = meta {
            spaces.push((s.virtual_base, s.virtual_base.saturating_add(s.size)));
        }
        let mut regions = Vec::new();
        let mut bsps = Vec::new();
        for t in map.tags().to_vec() {
            let Some(l) = t.location else { continue };
            if Some(l.space) == meta {
                if l.size > 0 {
                    regions.push((l.address, map.read_tag_bytes(t.id)?));
                }
            } else {
                let r = (
                    l.space.virtual_base,
                    l.space.virtual_base.saturating_add(l.space.size),
                );
                if !spaces.contains(&r) {
                    spaces.push(r);
                    bsps.push((
                        u32::try_from(l.space.file_offset).unwrap_or(u32::MAX),
                        l.space.size,
                        l.space.virtual_base,
                    ));
                }
            }
        }
        regions.sort_by_key(|r| r.0);
        Ok(Memory {
            regions,
            spaces,
            bsps,
        })
    }

    /// Memory holding only these regions (for tests and BSP tags).
    pub fn from_regions(mut regions: Vec<(u32, Vec<u8>)>, spaces: Vec<(u32, u32)>) -> Self {
        regions.sort_by_key(|r| r.0);
        Memory {
            regions,
            spaces,
            bsps: Vec::new(),
        }
    }

    /// The same, with these BSP regions (file offset, size, load address)
    /// for [`Field::Bsp`].
    pub fn with_bsps(mut self, bsps: Vec<(u32, u32, u32)>) -> Self {
        self.bsps = bsps;
        self
    }

    /// The region (address, bytes) holding `address`.
    pub fn region(&self, address: u32) -> Option<(u32, &[u8])> {
        let i = self
            .regions
            .partition_point(|r| r.0 <= address)
            .checked_sub(1)?;
        let (a, b) = &self.regions[i];
        (address - a < b.len() as u32).then_some((*a, b.as_slice()))
    }

    /// Overwrite bytes at `address` (inside one region). False when the
    /// range is in no region.
    pub fn patch(&mut self, address: u32, bytes: &[u8]) -> bool {
        let i = match self
            .regions
            .partition_point(|r| r.0 <= address)
            .checked_sub(1)
        {
            Some(i) => i,
            None => return false,
        };
        let (a, b) = &mut self.regions[i];
        let at = (address - *a) as usize;
        match b.get_mut(at..at + bytes.len()) {
            Some(d) => {
                d.copy_from_slice(bytes);
                true
            }
            None => false,
        }
    }

    /// `n` bytes at `address`, inside one region.
    pub fn slice(&self, address: u32, n: u32) -> Option<&[u8]> {
        let (a, b) = self.region(address)?;
        let at = (address - a) as usize;
        b.get(at..at.checked_add(n as usize)?)
    }

    fn hit(&self, v: u32) -> bool {
        self.spaces.iter().any(|&(lo, hi)| (lo..hi).contains(&v))
    }
}

/// Where a [`walk`] refused: the reason, the field path (block offsets from
/// the root) and the offset in the element (or in the tag, for coverage).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Detail {
    /// Why.
    pub refusal: Refusal,
    /// Offsets of the blocks followed from the root.
    pub path: Vec<u32>,
    /// Offset in the element, or in the tag for [`Refusal::Overlap`] and
    /// [`Refusal::Uncovered`].
    pub offset: u32,
    /// The value found (for [`Refusal::UnknownPointer`]).
    pub value: u32,
}

/// Walk the tag at `address` (its bytes in `mem`) with `root`. The arrays
/// inside the tag must tile it (exact duplicates allowed: the compiler
/// shares identical blocks), arrays outside it must sit inside one other
/// tag, and no undescribed word may hold an address in a known space.
pub fn walk(root: &Struct, address: u32, mem: &Memory) -> Result<Walk, Detail> {
    let fail = |refusal, path: &[u32], offset, value| Detail {
        refusal,
        path: path.to_vec(),
        offset,
        value,
    };
    let Some((start, own)) = mem.region(address).filter(|r| r.0 == address) else {
        return Err(fail(Refusal::NoData, &[], 0, address));
    };
    debug_assert_eq!(start, address);
    let len = own.len() as u32;
    let end = address + len;
    let mut out = Walk::default();
    // (struct, address, count, path)
    let mut todo: Vec<(&Struct, u32, u32, Vec<u32>)> = vec![(root, address, 1, Vec::new())];
    let mut seen = std::collections::HashSet::new();
    // Largest alignment of an array starting at each offset in the tag.
    let mut aligns = std::collections::HashMap::new();
    while let Some((s, at, count, path)) = todo.pop() {
        let n = u64::from(s.size) * u64::from(count);
        let Some(bytes) = u32::try_from(n).ok().and_then(|n| mem.slice(at, n)) else {
            return Err(fail(Refusal::OutOfBounds, &path, at, count));
        };
        let n = n as u32;
        // Shared arrays are followed once per layout.
        if !seen.insert((at, n, s as *const Struct)) {
            continue;
        }
        let own = (address..end).contains(&at);
        if own {
            out.arrays.push((at - address, n));
            let a = aligns.entry(at - address).or_insert(1);
            *a = (*a).max(s.align);
        } else {
            out.foreign.push((at, n));
        }
        for i in 0..count {
            let e = (i * s.size) as usize;
            let elem = &bytes[e..e + s.size as usize];
            let mut covered = vec![false; elem.len()];
            // Raw fields are checked too: one holding an address is a
            // misclassified pointer.
            for (&o, f) in s.fields.iter().filter(|(_, f)| !matches!(f, Field::Raw)) {
                covered[o as usize..(o + f.width()) as usize].fill(true);
            }
            for (&o, _) in s.fields.iter().filter(|(_, f)| matches!(f, Field::Bsp)) {
                let w = |k: u32| u32_at(elem, (o + k) as usize);
                let t = (w(0), w(4), w(8));
                if t != (0, 0, 0) && !mem.bsps.contains(&t) {
                    return Err(fail(Refusal::UnknownPointer, &path, o + 8, t.2));
                }
            }
            for k in (0..elem.len().saturating_sub(3)).step_by(4) {
                if covered[k..k + 4].iter().any(|c| *c) {
                    continue;
                }
                let v = u32_at(elem, k);
                if (address..end).contains(&v) || mem.hit(v) {
                    return Err(fail(Refusal::UnknownPointer, &path, k as u32, v));
                }
            }
            for (&o, f) in &s.fields {
                if let Field::Block(child) = f {
                    let c = u32_at(elem, o as usize);
                    let a = u32_at(elem, o as usize + 4);
                    let mut sub = path.clone();
                    sub.push(o);
                    // Empty (the builder writes address zero), or a count
                    // with a null address, kept as bytes.
                    if c == 0 || a == 0 {
                        continue;
                    }
                    if own {
                        out.pointers.push((at - address + (e as u32) + o, c, a));
                    }
                    todo.push((child, a, c, sub));
                }
            }
        }
    }
    out.arrays.sort_unstable();
    out.arrays.dedup();
    out.pointers.sort_unstable();
    out.pointers.dedup();
    let mut pos = 0u32;
    for &(at, n) in &out.arrays {
        if n == 0 {
            continue;
        }
        if at < pos {
            return Err(fail(Refusal::Overlap, &[], at, pos));
        }
        // Or whatever (stale bytes) precedes an array placed on its
        // alignment, when shorter than it: no pointer in the tag reaches
        // those bytes (the check above), so they are the compiler's
        // alignment padding.
        let align = aligns.get(&at).copied().unwrap_or(1);
        let aligned = (address + at).is_multiple_of(align) && at - pos < align;
        if at - pos >= MAX_ALIGN || !(aligned || padding(&own[pos as usize..at as usize], pos)) {
            return Err(fail(Refusal::Uncovered, &[], pos, at - pos));
        }
        pos = at + n;
    }
    if len - pos >= MAX_ALIGN || !padding(&own[pos as usize..], pos) {
        return Err(fail(Refusal::Uncovered, &[], pos, len - pos));
    }
    Ok(out)
}

/// Whether the gap `bytes` at offset `pos` (shorter than [`MAX_ALIGN`]) is
/// alignment padding: zero, or the debug heap's uninitialised `0xcd` fill,
/// or any 1-3 bytes up to the next word (retail leaves those unwritten
/// after arrays of 2- and 6-byte elements).
fn padding(bytes: &[u8], pos: u32) -> bool {
    bytes.iter().all(|b| *b == 0)
        || bytes.iter().all(|b| *b == 0xcd)
        || (bytes.len() as u32) == pos.next_multiple_of(4) - pos
}

/// Structural hash of a layout, so equal layouts reached from different
/// groups share blocks.
fn layout_hash(s: &Struct, h: &mut impl std::hash::Hasher) {
    use std::hash::Hash;
    (s.size, s.align, s.fields.len()).hash(h);
    for (o, f) in &s.fields {
        o.hash(h);
        match f {
            Field::Block(c) => {
                0u8.hash(h);
                layout_hash(c, h);
            }
            Field::TagRef => 1u8.hash(h),
            Field::TagId => 2u8.hash(h),
            Field::StringId => 3u8.hash(h),
            Field::Raw => 4u8.hash(h),
            Field::Bsp => 5u8.hash(h),
            Field::Word => 6u8.hash(h),
            Field::RawSize(of) => {
                7u8.hash(h);
                of.hash(h);
            }
        }
    }
}

/// What [`tree`] needs besides the layout.
struct TreeCtx<'a> {
    mem: &'a Memory,
    /// Distinguishes maps, so keys from two maps never meet in one set.
    salt: u64,
    /// The tag being built: (address, end).
    own: (u32, u32),
    /// Whether the tag holding an array outside `own` keeps its address
    /// (then the pointer stays as it is, with no copy).
    stays: &'a dyn Fn(u32) -> bool,
}

/// Build the block tree for `count` elements of `s` at `at`. Every array is
/// keyed by its source address, length and layout, so the builder places an
/// array shared between tags (or within one) once. An array in another tag
/// that keeps its address is not copied: the pointer bytes stay. Tag
/// references, datums and string IDs keep their bytes: in the same tag set
/// they stay valid. Moving tags between maps rewrites them (see [`remap`]).
fn tree(s: &Struct, cx: &TreeCtx, at: u32, count: u32) -> Block {
    use std::hash::Hasher;
    let n = s.size * count;
    let bytes = cx.mem.slice(at, n).expect("walked");
    let mut h = std::collections::hash_map::DefaultHasher::new();
    h.write_u64(cx.salt);
    h.write_u32(at);
    h.write_u32(n);
    layout_hash(s, &mut h);
    let mut block = Block::new(bytes.to_vec())
        .aligned(s.align)
        .shared(h.finish());
    for i in 0..count {
        let e = (i * s.size) as usize;
        for (&o, f) in &s.fields {
            if let Field::Block(child) = f {
                let c = u32_at(bytes, e + o as usize);
                let a = u32_at(bytes, e + o as usize + 4);
                if c != 0 && a == 0 {
                    // A count with a null address: no child, bytes kept.
                    continue;
                }
                let foreign = !(cx.own.0..cx.own.1).contains(&a);
                if c != 0 && foreign && (cx.stays)(a) {
                    continue;
                }
                let sub = if c == 0 {
                    Block::zeroed(0).aligned(child.align)
                } else {
                    tree(child, cx, a, c)
                };
                let off = i * s.size + o;
                if child.size == 1 && child.fields.is_empty() {
                    block.fixup(off, FixupKind::Data(sub));
                } else {
                    block.block(off, c, sub);
                }
            }
        }
    }
    block
}

/// Relocates the tags of one map with a schema.
pub struct Relocator<'s> {
    schema: &'s Schema,
    memory: Memory,
    tags: Vec<map::Tag>,
    by_id: std::collections::HashMap<TagId, usize>,
    /// Ordinary-metadata tag by its address.
    by_address: std::collections::HashMap<u32, TagId>,
    metadata: Option<map::AddressSpace>,
    salt: u64,
}

impl<'s> Relocator<'s> {
    /// Read `map`'s metadata once.
    pub fn new<R: Read + Seek>(schema: &'s Schema, map: &mut Map<R>) -> crate::Result<Self> {
        let tags = map.tags().to_vec();
        let metadata = map.metadata_space();
        let h = map.header();
        let salt = u64::from(h.checksum) << 32 | u64::from(h.file_size);
        Ok(Relocator {
            schema,
            memory: Memory::of(map)?,
            by_id: tags.iter().enumerate().map(|(i, t)| (t.id, i)).collect(),
            by_address: tags
                .iter()
                .filter_map(|t| {
                    let l = t.location?;
                    (Some(l.space) == metadata && l.size > 0).then_some((l.address, t.id))
                })
                .collect(),
            tags,
            metadata,
            salt,
        })
    }

    /// The map's metadata.
    pub fn memory(&self) -> &Memory {
        &self.memory
    }

    /// The map's metadata, to patch words a caller replaces anyway (such
    /// as a scenario's BSP descriptor addresses, which point into BSP
    /// space and so stop [`Relocator::check`]).
    pub fn memory_mut(&mut self) -> &mut Memory {
        &mut self.memory
    }

    fn tag(&self, id: TagId) -> Option<&map::Tag> {
        self.by_id.get(&id).map(|&i| &self.tags[i])
    }

    /// The tag whose bytes hold `address`.
    pub fn owner(&self, address: u32) -> Option<TagId> {
        let (start, _) = self.memory.region(address)?;
        self.by_address.get(&start).copied()
    }

    /// Check one tag; `Ok` means [`Relocator::to_built`] will succeed.
    pub fn check(&self, id: TagId) -> Result<Walk, Detail> {
        let fail = |refusal| Detail {
            refusal,
            path: Vec::new(),
            offset: 0,
            value: 0,
        };
        let tag = self.tag(id).ok_or(fail(Refusal::NoData))?;
        let Some(root) = self.schema.groups.get(&tag.group) else {
            return Err(fail(Refusal::NoSchema));
        };
        match tag.location {
            None => Err(fail(Refusal::NoData)),
            Some(l) if Some(l.space) != self.metadata => Err(fail(Refusal::BspRegion)),
            Some(l) => walk(root, l.address, &self.memory),
        }
    }

    /// The tag as a relocatable tree, or why not. Arrays it shares with
    /// other tags are copied into the tree (keyed, so the builder still
    /// places each once). When the set of moving tags is known, use
    /// [`Relocator::to_built_among`].
    pub fn to_built(&self, id: TagId) -> Result<Block, Refusal> {
        self.build(id, &|_| false)
    }

    /// [`Relocator::to_built`] for a tag some of whose fields the caller
    /// emptied (patched in [`Relocator::memory_mut`]): its arrays need not
    /// tile it, since the emptied fields' old arrays are left out. Every
    /// other check holds. Whether other tags point into it is
    /// [`Relocator::pointed_into`].
    pub fn to_built_emptied(&self, id: TagId) -> Result<Block, Detail> {
        match self.check(id) {
            Ok(_) => {}
            Err(d) if d.refusal == Refusal::Uncovered => {}
            Err(d) => return Err(d),
        }
        let tag = self.tag(id).expect("checked");
        let root = &self.schema.groups[&tag.group];
        let l = tag.location.expect("checked");
        let cx = TreeCtx {
            mem: &self.memory,
            salt: self.salt,
            own: (l.address, l.address + l.size),
            stays: &|_| false,
        };
        let mut block = tree(root, &cx, l.address, 1);
        block.share = None;
        Ok(block)
    }

    /// Arrays of other tags (by their schema, followed from each root)
    /// that sit inside `id`'s bytes, as (that tag, address, byte length).
    /// `id`'s bytes can be freed only when there are none, or when these
    /// ranges are kept. Words that merely fall inside `id` (shader
    /// microcode, sample data) are not counted.
    pub fn pointed_into(&self, id: TagId) -> Vec<(TagId, u32, u32)> {
        let Some(t) = self.tag(id) else {
            return Vec::new();
        };
        let Some(l) = t.location else {
            return Vec::new();
        };
        let range = l.address..l.address + l.size;
        let mut out = Vec::new();
        for other in &self.tags {
            let (Some(ol), Some(root)) = (other.location, self.schema.groups.get(&other.group))
            else {
                continue;
            };
            if other.id == id || Some(ol.space) != self.metadata || ol.size == 0 {
                continue;
            }
            let mut seen = std::collections::HashSet::new();
            let mut todo = vec![(root, ol.address, 1u32, 0u32)];
            while let Some((s, at, count, depth)) = todo.pop() {
                if depth > 64 || !seen.insert(at) {
                    continue;
                }
                let Some(bytes) = s
                    .size
                    .checked_mul(count)
                    .and_then(|n| self.memory.slice(at, n))
                else {
                    continue;
                };
                for i in 0..count {
                    let e = (i * s.size) as usize;
                    for (&o, f) in &s.fields {
                        if let Field::Block(child) = f {
                            let c = u32_at(bytes, e + o as usize);
                            let a = u32_at(bytes, e + o as usize + 4);
                            if c == 0 || a == 0 {
                                continue;
                            }
                            if range.contains(&a) {
                                out.push((other.id, a, c.saturating_mul(child.size)));
                            }
                            todo.push((child, a, c, depth + 1));
                        }
                    }
                }
            }
        }
        out
    }

    /// [`Relocator::to_built`] when exactly the tags in `moving` become
    /// built: arrays in any other tag stay where they are and are not copied.
    pub fn to_built_among(
        &self,
        id: TagId,
        moving: &std::collections::HashSet<TagId>,
    ) -> Result<Block, Refusal> {
        self.build(id, &|a| self.owner(a).is_none_or(|o| !moving.contains(&o)))
    }

    fn build(&self, id: TagId, stays: &dyn Fn(u32) -> bool) -> Result<Block, Refusal> {
        self.check(id).map_err(|d| d.refusal)?;
        let tag = self.tag(id).expect("checked");
        let root = &self.schema.groups[&tag.group];
        let l = tag.location.expect("checked");
        let cx = TreeCtx {
            mem: &self.memory,
            salt: self.salt,
            own: (l.address, l.address + l.size),
            stays,
        };
        let mut block = tree(root, &cx, l.address, 1);
        // Roots are never shared.
        block.share = None;
        Ok(block)
    }

    /// The tag as one flat block in its **source layout**: its bytes as
    /// they are, with every block and data-reference field a
    /// [`FixupKind::TagOffset`] into the tag that holds the target (itself,
    /// or another tag for shared blocks). Its size never changes, and its
    /// address keeps its old phase modulo 16, so arrays stay aligned. The
    /// target tags must be in the same set (moved or pinned).
    pub fn to_built_source(&self, id: TagId) -> Result<Block, Refusal> {
        let walk = self.check(id).map_err(|d| d.refusal)?;
        let tag = self.tag(id).expect("checked");
        let l = tag.location.expect("checked");
        if l.size == 0 {
            // An alias of another tag's bytes: nothing of its own to keep.
            return Err(Refusal::NoData);
        }
        let bytes = self.memory.slice(l.address, l.size).expect("walked");
        let mut block = Block::new(bytes.to_vec()).aligned(MAX_ALIGN);
        block.phase = l.address % MAX_ALIGN;
        for (pos, count, target) in walk.pointers {
            let owner = self.owner(target).ok_or(Refusal::OutOfBounds)?;
            let start = self.memory.region(target).expect("owned").0;
            block.fixup(
                pos,
                FixupKind::TagOffset {
                    count,
                    tag: owner,
                    offset: target - start,
                },
            );
        }
        Ok(block)
    }

    /// Replace each tag of `ids` in `set` (decomposed from this map) with
    /// its built tree, sharing what the source shares. `ids` should come
    /// from [`Relocator::movable`]. With `source_layout`, each tag keeps its
    /// source layout ([`Relocator::to_built_source`]); otherwise children
    /// are laid out depth first ([`Relocator::to_built_among`]).
    pub fn relocate(
        &self,
        set: &mut map::build::TagSet,
        ids: &[TagId],
        source_layout: bool,
    ) -> crate::Result<()> {
        let moving: std::collections::HashSet<TagId> = ids.iter().copied().collect();
        let empty = |id: TagId| {
            self.tag(id)
                .and_then(|t| t.location)
                .is_none_or(|l| l.size == 0)
        };
        for &id in ids.iter().filter(|id| !empty(**id)) {
            let block = if source_layout {
                self.to_built_source(id)
            } else {
                self.to_built_among(id, &moving)
            }
            .map_err(|_| crate::Error::Invalid("tag is not relocatable"))?;
            set.tag_mut(id)
                .ok_or(crate::Error::Invalid("tag not in the set"))?
                .payload = map::build::TagPayload::Built(block);
        }
        // Retail has tags of index size 0 at another tag's address (whole
        // tags the compiler shared). Each follows its target when it moves.
        for t in &self.tags {
            let Some(l) = t
                .location
                .filter(|l| l.size == 0 && Some(l.space) == self.metadata)
            else {
                continue;
            };
            let Some(owner) = self.owner(l.address).filter(|o| moving.contains(o)) else {
                continue;
            };
            let start = self.memory.region(l.address).expect("owned").0;
            if let Some(e) = set.tag_mut(t.id) {
                e.payload = map::build::TagPayload::Alias {
                    tag: owner,
                    offset: l.address - start,
                };
            }
        }
        Ok(())
    }

    /// Tags that can move together: every tag [`Relocator::check`] accepts,
    /// minus those a staying tag points into (any aligned word of a pinned
    /// tag holding an address inside them), repeated until nothing changes.
    pub fn movable(&self) -> Vec<TagId> {
        self.movable_where(|_| true)
    }

    /// [`Relocator::movable`], starting from the accepted tags whose walk
    /// passes `keep` (e.g. no shared arrays, which the tree copies and so
    /// grows the metadata).
    pub fn movable_where(&self, keep: impl Fn(&Walk) -> bool) -> Vec<TagId> {
        let mut ok: std::collections::BTreeSet<u32> = self
            .tags
            .iter()
            .filter(|t| self.check(t.id).is_ok_and(|w| keep(&w)))
            .map(|t| t.location.expect("checked").address)
            .collect();
        loop {
            let mut pinned_targets = Vec::new();
            for (a, bytes) in &self.memory.regions {
                if ok.contains(a) {
                    continue;
                }
                for w in bytes.as_chunks::<4>().0 {
                    let v = u32::from_le_bytes(*w);
                    if let Some((t, _)) = self.memory.region(v)
                        && t != *a
                        && ok.contains(&t)
                    {
                        pinned_targets.push(t);
                    }
                }
            }
            if pinned_targets.is_empty() {
                break;
            }
            for t in pinned_targets {
                ok.remove(&t);
            }
        }
        self.tags
            .iter()
            .filter(|t| {
                t.location
                    .is_some_and(|l| Some(l.space) == self.metadata && ok.contains(&l.address))
            })
            .map(|t| t.id)
            .collect()
    }
}

/// Load-test variant "relocated": `map` decomposed, and every tag
/// [`Relocator::movable`] allows (except slot 0, which the builder needs
/// first in the metadata) rebuilt from the checked-in schema, sharing what
/// the source shares. With `reverse`, built tags are placed in reverse slot
/// order so they land away from their old addresses. Returns the set and the
/// rebuilt tags.
pub fn relocated_variant<R: Read + Seek>(
    map: &mut Map<R>,
    reverse: bool,
    source_layout: bool,
) -> crate::Result<(map::build::TagSet, Vec<TagId>)> {
    let relocator = Relocator::new(Schema::builtin(), map)?;
    let ids: Vec<TagId> = relocator
        .movable()
        .into_iter()
        .filter(|id| id.index() != 0)
        .collect();
    let mut set = map::build::TagSet::from_map(map)?;
    set.reverse_built = reverse;
    relocator.relocate(&mut set, &ids, source_layout)?;
    Ok((set, ids))
}

/// Turn the tag `id` of `map` into a relocatable block tree with `schema`.
/// Reads the map's whole metadata; for many tags use a [`Relocator`].
pub fn to_built_with<R: Read + Seek>(
    schema: &Schema,
    map: &mut Map<R>,
    id: TagId,
) -> crate::Result<Result<Block, Refusal>> {
    Ok(Relocator::new(schema, map)?.to_built(id))
}

/// [`to_built_with`] using the checked-in schema.
pub fn to_built<R: Read + Seek>(
    map: &mut Map<R>,
    id: TagId,
) -> crate::Result<Result<Block, Refusal>> {
    to_built_with(Schema::builtin(), map, id)
}

/// A decoded tag tree with every address removed: each array's element
/// bytes with block addresses zeroed, followed by its children in field
/// order. Two tags with equal trees hold the same data wherever they sit.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Tree {
    /// Element bytes, block address words zeroed.
    pub bytes: Vec<u8>,
    /// Child arrays, in element then field order.
    pub children: Vec<Tree>,
}

/// Read the address-free [`Tree`] of the tag at `address`.
pub fn read_tree(root: &Struct, address: u32, mem: &Memory) -> Option<Tree> {
    fn go(s: &Struct, mem: &Memory, at: u32, count: u32, depth: u32) -> Option<Tree> {
        if depth > 64 {
            return None;
        }
        let mut own = mem.slice(at, s.size.checked_mul(count)?)?.to_vec();
        let mut children = Vec::new();
        for i in 0..count {
            let e = (i * s.size) as usize;
            for (&o, f) in &s.fields {
                if let Field::Block(child) = f {
                    let o = e + o as usize;
                    let c = u32_at(&own, o);
                    let a = u32_at(&own, o + 4);
                    own[o + 4..o + 8].fill(0);
                    children.push(if c == 0 || a == 0 {
                        Tree {
                            bytes: Vec::new(),
                            children: Vec::new(),
                        }
                    } else {
                        go(child, mem, a, c, depth + 1)?
                    });
                }
            }
        }
        Some(Tree {
            bytes: own,
            children,
        })
    }
    go(root, mem, address, 1, 0)
}

/// What [`visit`] calls per element: layout, element bytes, block path.
pub type Visitor<'a> = dyn FnMut(&Struct, &[u8], &[u32]) + 'a;

/// Visit every element of the tag at `address` in a fixed order (each
/// element, then its children in field order): `f` gets the layout, the
/// element's bytes and the block path. Shared arrays are visited each time
/// they are reached. `None` if a block runs outside the memory.
pub fn visit(root: &Struct, address: u32, mem: &Memory, f: &mut Visitor) -> Option<()> {
    fn go(
        s: &Struct,
        mem: &Memory,
        at: u32,
        count: u32,
        path: &mut Vec<u32>,
        f: &mut Visitor,
    ) -> Option<()> {
        if path.len() > 64 {
            return None;
        }
        let bytes = mem.slice(at, s.size.checked_mul(count)?)?;
        for i in 0..count {
            let e = &bytes[(i * s.size) as usize..((i + 1) * s.size) as usize];
            f(s, e, path);
            for (&o, fl) in &s.fields {
                if let Field::Block(child) = fl {
                    let c = u32_at(e, o as usize);
                    let a = u32_at(e, o as usize + 4);
                    if c != 0 && a != 0 {
                        path.push(o);
                        go(child, mem, a, c, path, f)?;
                        path.pop();
                    }
                }
            }
        }
        Some(())
    }
    go(root, mem, address, 1, &mut Vec::new(), f)
}

/// How [`remap`] translates IDs from a source map into a destination set.
pub trait Remapper {
    /// The destination datum for a source datum, or `None` to null it.
    fn datum(&mut self, source: u32) -> Option<u32>;
    /// The destination string ID for a non-zero source string ID.
    fn string(&mut self, source: u32) -> u32;
    /// Where a non-null source raw pointer goes: `size` is its paired
    /// [`Field::RawSize`] value, `siblings` the element's other raw
    /// pointers (a resource may span theirs: a bitmap's first level of
    /// detail holds the later ones).
    fn raw(&mut self, source: u32, size: Option<u32>, siblings: &[u32]) -> RawRef;
}

/// Rewrite the tag references, datums, string IDs and raw pointers of a
/// tree built from one map (`count` elements of `s`) so it is valid in
/// another. A tag reference whose datum maps to `None` becomes null (group
/// and datum `0xffffffff`). Shared blocks are rewritten wherever they
/// appear, identically, so their sharing keys stay truthful.
pub fn remap(s: &Struct, block: &mut Block, count: u32, r: &mut dyn Remapper) {
    let put =
        |b: &mut Block, at: usize, v: u32| b.bytes[at..at + 4].copy_from_slice(&v.to_le_bytes());
    for i in 0..count {
        for (&o, f) in &s.fields {
            let at = (i * s.size + o) as usize;
            match f {
                Field::TagRef => {
                    let d = u32_at(&block.bytes, at + 4);
                    if d != u32::MAX {
                        match r.datum(d) {
                            Some(nd) => put(block, at + 4, nd),
                            None => {
                                put(block, at, u32::MAX);
                                put(block, at + 4, u32::MAX);
                            }
                        }
                    }
                }
                Field::TagId => {
                    let d = u32_at(&block.bytes, at);
                    if d != u32::MAX {
                        let nd = r.datum(d).unwrap_or(u32::MAX);
                        put(block, at, nd);
                    }
                }
                Field::StringId => {
                    let v = u32_at(&block.bytes, at);
                    if v != 0 {
                        let nv = r.string(v);
                        put(block, at, nv);
                    }
                }
                Field::Raw => {
                    let v = u32_at(&block.bytes, at);
                    if v != 0 && v != u32::MAX {
                        let e = (i * s.size) as usize;
                        let size = s.fields.iter().find_map(|(&k, f)| {
                            matches!(f, Field::RawSize(of) if *of == o)
                                .then(|| u32_at(&block.bytes, e + k as usize))
                        });
                        let siblings: Vec<u32> = s
                            .fields
                            .iter()
                            .filter(|(k, f)| **k != o && matches!(f, Field::Raw))
                            .map(|(&k, _)| u32_at(&block.bytes, e + k as usize))
                            .collect();
                        match r.raw(v, size, &siblings) {
                            RawRef::Null => put(block, at, u32::MAX),
                            RawRef::External { file, offset } => {
                                let sel = match file {
                                    map::ResourceFile::Local => 0,
                                    map::ResourceFile::MainMenu => 1,
                                    map::ResourceFile::Shared => 2,
                                    map::ResourceFile::SinglePlayerShared => 3,
                                };
                                put(block, at, sel << 30 | offset);
                            }
                            local @ RawRef::Local(_) => {
                                put(block, at, 0);
                                block.raw(at as u32, local);
                            }
                        }
                    }
                }
                // Another map's BSP regions mean nothing here; a transplant
                // that brings a scenario rewrites them itself.
                Field::Bsp | Field::Word | Field::RawSize(_) => {}
                Field::Block(child) => {
                    let off = i * s.size + o;
                    let c = u32_at(&block.bytes, at);
                    if let Some(fx) = block.fixups.iter_mut().find(|x| x.offset == off) {
                        match &mut fx.kind {
                            FixupKind::Block { child: sub, .. } | FixupKind::Data(sub) => {
                                remap(child, sub, c, r);
                            }
                            _ => {}
                        }
                    }
                }
            }
        }
    }
}

