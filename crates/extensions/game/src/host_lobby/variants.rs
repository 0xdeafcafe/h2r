//! Variant names accepted by the host. The catalogue is built once at boot;
//! handling an RPC in a tick never opens a save or reads the disc.
use std::fs::File;
use std::io::BufReader;
use std::path::Path;

use ::variants::{GameVariant, Schema, save::SaveStore};
use anyhow::Context;
use live_proto::hopper::{defaults, variant::VariantRecord};

use super::{Variant, invalid};
use crate::new_maps::Disc;

#[derive(Default)]
pub(super) struct Variants {
    // Keep duplicates: two variants with the same name but different rules
    // must not silently select whichever save directory was read first.
    named: Vec<(String, VariantRecord)>,
}

impl Variants {
    pub(super) fn load(disc: &mut dyn Disc, data_root: &Path) -> anyhow::Result<Self> {
        let mut out = Self::default();
        let file = disc
            .map_file("mainmenu")?
            .context("host lobby needs mainmenu.map")?;
        let mut map = map::Map::from_region(
            BufReader::new(File::open(&file.path)?),
            file.offset,
            file.len,
        )?;
        match Schema::from_map(&mut map, tags::Language::English) {
            Ok(schema) => {
                for builtin in &schema.builtins {
                    if let Ok(v) = schema.build(builtin) {
                        out.add(&builtin.name, v);
                    }
                }
            }
            // Base game types are generated by retail and Live playlist keys
            // carry their own record even on a stripped owner-supplied map.
            Err(e) => eprintln!("host-lobby: disc variant names unavailable: {e}"),
        }
        let store = SaveStore::new(SaveStore::root_under(data_root), None);
        for save in store.list()? {
            let v = save.contents.variant;
            if save.contents.signed && ::variants::record::refused(&v).is_empty() {
                out.add(&v.name(), v);
            }
        }
        Ok(out)
    }

    fn add(&mut self, name: &str, variant: GameVariant) {
        if let Some(record) = VariantRecord::from_bytes(variant.bytes()) {
            self.named.push((name.to_lowercase(), record));
        }
    }

    pub(super) fn resolve(&self, name: Option<&str>) -> Result<Variant, agent_proto::RpcError> {
        let Some(name) = name else {
            return Ok(Variant::Stock(sim_bench::config::GameType::Slayer));
        };
        let name = name.trim();
        if name.is_empty() || name.encode_utf16().count() > 63 || name.chars().any(char::is_control)
        {
            return Err(invalid("invalid variant name"));
        }
        let key = name.to_lowercase();
        let mut exact = self.named.iter().filter(|(label, _)| label == &key);
        if let Some((_, record)) = exact.next() {
            if exact.any(|(_, other)| other != record) {
                return Err(invalid(format!("more than one variant named {name:?}")));
            }
            return Ok(Variant::Named(Box::new(record.clone())));
        }
        if name
            .bytes()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, b' ' | b'_' | b'-'))
        {
            if let Ok(ty) = sim_bench::config::GameType::parse(name) {
                return Ok(Variant::Stock(ty));
            }
            if let Some(v) = defaults::builtin_variant(&key.replace([' ', '-'], "_")) {
                return Ok(Variant::Named(Box::new(v)));
            }
        }
        Err(invalid(format!("unknown game variant {name:?}")))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn resolves_custom_names_literally_and_refuses_conflicting_rules() {
        let mut catalog = Variants::default();
        let mut variant = GameVariant::blank(::variants::GameType::Slayer);
        variant.set_name("Alex's mêlée").unwrap();
        catalog.add("Alex's mêlée", variant.clone());
        assert!(matches!(
            catalog.resolve(Some("ALEX'S MÊLÉE")).unwrap(),
            Variant::Named(_)
        ));
        catalog.add("Alex's mêlée", variant.clone());
        assert!(catalog.resolve(Some("Alex's mêlée")).is_ok());
        variant.set(::variants::SettingId(2), 10).unwrap();
        catalog.add("Alex's mêlée", variant);
        assert!(catalog.resolve(Some("Alex's mêlée")).is_err());
    }
}
