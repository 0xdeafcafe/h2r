#!/usr/bin/env python3
"""Regenerate the crate table in docs/ARCHITECTURE.md from the manifests.

    scripts/crate-table.py            rewrite the table in place
    scripts/crate-table.py --check    exit 1 if the table is out of date
    scripts/crate-table.py --strict   as --check, and every crate must have a
                                      description and a domain
    scripts/crate-table.py --stdout   print the table and leave the file alone

A row comes from the crate's own Cargo.toml and its place in the tree, so
a lane that adds a crate adds its row with it (docs/dev/crate-structure.md,
"The crate table"):

    crates/<domain>/<crate>/Cargo.toml   # the domain column is the directory
    [package]
    description = "One line: what the crate is for"

    [package.metadata.h2]
    status = "done"                      # optional
    doc = ["runtime/storage.md"]         # optional, paths under docs/

While a crate still sits flat in crates/, its domain is the one
scripts/crate-domains.toml plans for it. Until every manifest carries a
description, a cell with no source keeps the text the table already has:
a purpose kept that way is marked with a dagger, and `--strict` refuses
it. Reads the manifests with scripts/cratemeta.py; cargo is not run.
"""
import os
import re
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cratemeta  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "docs", "ARCHITECTURE.md")
BEGIN = "<!-- crate-table:begin (generated by scripts/crate-table.py from the Cargo.toml descriptions; do not edit) -->"
END = "<!-- crate-table:end -->"
DAGGER = " †"
NOTE = (
    "† Written here by hand. The text belongs in the crate's `Cargo.toml` "
    "`description`; `scripts/crate-table.py --strict` fails until it is there."
)
LINK = re.compile(r"\[[^\]]+\]\([^)]+\)")
DOC_PATH = re.compile(r"\bdocs/([A-Za-z0-9_./-]+\.md)")


def packages():
    """Every package, with its domain under ["domain"]."""
    rule_set = cratemeta.rules(ROOT)
    pkgs = cratemeta.packages(ROOT)
    for p in pkgs.values():
        p["domain"] = cratemeta.domain_of(p, rule_set, ROOT)[0] or ""
    return sorted(pkgs.values(), key=lambda p: p["name"]), list(rule_set["domains"])


def cells(line):
    """The cells of one markdown table row. Splits on unescaped bars."""
    parts = re.split(r"(?<!\\)\|", line.strip())
    return [c.strip() for c in parts[1:-1]]


def existing(lines):
    """Rows already in the table, by crate name: {name: {column: cell}}."""
    rows, header = {}, None
    for line in lines:
        if not line.lstrip().startswith("|"):
            continue
        c = cells(line)
        if header is None:
            header = [h.lower() for h in c]
            continue
        if c and set(c[0]) <= set("-: "):
            continue
        m = re.match(r"`([^`]+)`", c[0]) if c else None
        if m:
            rows[m.group(1)] = dict(zip(header, c))
    return rows


def builds(p):
    """What the crate links besides an rlib: `bin h2`, `staticlib h2host`."""
    out = []
    for t in p["targets"]:
        kind = t["kind"][0]
        if kind == "bin":
            out.append(f"bin `{t['name']}`")
        elif kind in ("cdylib", "staticlib", "dylib"):
            out.append(f"{kind} `{t['name']}`")
        elif "staticlib" in t["kind"] or "cdylib" in t["kind"]:
            extra = [k for k in t["kind"] if k in ("staticlib", "cdylib")]
            out.append(f"{extra[0]} `{t['name']}`")
    return ", ".join(out)


def doc_links(paths):
    return ", ".join(f"[{os.path.basename(p)}]({p})" for p in paths)


def row(p, old, with_layer):
    name = p["name"]
    meta = ((p.get("metadata") or {}).get("h2")) or {}
    described = bool(p.get("description"))
    if described:
        purpose = " ".join(p["description"].split())
    else:
        kept = old.get("purpose", "").removesuffix(DAGGER.strip()).strip()
        purpose = (kept + DAGGER) if kept else "*(no description)*" + DAGGER
    docs = meta.get("doc")
    if isinstance(docs, str):
        docs = [docs]
    if docs:
        links = doc_links(docs)
    else:
        found = DOC_PATH.findall(p.get("description") or "")
        kept = LINK.findall(old.get("docs", "")) or LINK.findall(old.get("purpose", ""))
        links = doc_links(found) if found else ", ".join(kept)
    status = meta.get("status") or old.get("status", "")
    crate = f"`{name}`"
    b = builds(p)
    if b:
        crate += f" ({b})"
    out = [crate]
    if with_layer:
        out.append(p["domain"])
    out += [purpose.replace("|", "\\|"), links, status]
    return "| " + " | ".join(out) + " |", described, p["domain"]


def table(pkgs, old, domains):
    with_layer = True
    order = {d: i for i, d in enumerate(domains)}
    pkgs = sorted(pkgs, key=lambda p: (order.get(p["domain"], len(order)), p["name"]))
    head = ["crate", "domain", "purpose", "docs", "status"]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    problems, dagger = [], False
    for p in pkgs:
        line, described, layer = row(p, old.get(p["name"], {}), with_layer)
        lines.append(line)
        if not described:
            dagger = True
            problems.append(f"{p['name']}: no `description` in its Cargo.toml")
        if layer not in order:
            problems.append(f"{p['name']}: no domain; add it to a `crates` list in {cratemeta.RULES}")
    if dagger:
        lines += ["", NOTE]
    return lines, problems


def main(argv):
    mode = argv[1] if len(argv) > 1 else ""
    if mode not in ("", "--check", "--strict", "--stdout"):
        sys.exit(__doc__)
    text = open(DOC, encoding="utf-8").read().split("\n")
    if BEGIN in text and END in text:
        a, b = text.index(BEGIN), text.index(END)
    else:
        # First run: adopt the hand-written table under "## Crates".
        start = next(i for i, l in enumerate(text) if l.lstrip().startswith("| crate"))
        end = start
        while end < len(text) and text[end].lstrip().startswith("|"):
            end += 1
        text[start:end] = [BEGIN] + text[start:end] + [END]
        a, b = start, end + 1
    pkgs, domains = packages()
    new, problems = table(pkgs, existing(text[a + 1 : b]), domains)
    result = text[:a] + [BEGIN] + new + [END] + text[b + 1 :]
    if mode == "--stdout":
        print("\n".join(new))
        return 0
    stale = result != open(DOC, encoding="utf-8").read().split("\n")
    if mode in ("--check", "--strict"):
        if stale:
            print("docs/ARCHITECTURE.md: the crate table is out of date; run scripts/crate-table.py", file=sys.stderr)
        if mode == "--strict":
            for p in problems:
                print(f"crate-table: {p}", file=sys.stderr)
        return 1 if stale or (mode == "--strict" and problems) else 0
    if stale:
        with open(DOC, "w", encoding="utf-8") as f:
            f.write("\n".join(result))
    print(f"docs/ARCHITECTURE.md: {len(new) - 2 - (2 if NOTE in new else 0)} crates" + ("" if stale else " (unchanged)"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
